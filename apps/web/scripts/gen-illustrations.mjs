// Turns design/illustrations/*.svg into React (src/components/illustrations/generated.tsx).
//   node scripts/gen-illustrations.mjs        (also: pnpm --filter @school-sync/web illustrations)
// The SVGs use six literal hex placeholders (see PLACEHOLDERS) that are replaced by CSS variables, so every school's
// illustrations pick up its colours automatically (the variables are defined in app/globals.css as --ill-*).
// No dependency: the SVGs are simple (rect / circle / path / g), converted with a small attribute mapper.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const SRC = resolve(new URL('../../../design/illustrations', import.meta.url).pathname);
const OUT = resolve(new URL('../src/components/illustrations/generated.tsx', import.meta.url).pathname);

/** literal placeholder (upper-case hex) → CSS variable */
const PLACEHOLDERS = {
  '#0E5A63': 'var(--ill-brand)',
  '#CFE6E8': 'var(--ill-brand-soft)',
  '#C9731A': 'var(--ill-accent)',
  '#FBEFD9': 'var(--ill-accent-soft)',
  '#F4F1EC': 'var(--ill-paper)',
  '#1C1A17': 'var(--ill-ink)',
};

const ATTRS = { 'stroke-width': 'strokeWidth', 'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin', 'stroke-dasharray': 'strokeDasharray', 'stroke-opacity': 'strokeOpacity', 'fill-opacity': 'fillOpacity', 'fill-rule': 'fillRule', 'clip-rule': 'clipRule', 'clip-path': 'clipPath', 'stop-color': 'stopColor', 'stop-opacity': 'stopOpacity', class: 'className' };

const esc = (s) => s.replace(/&/g, '&amp;').replace(/'/g, '&apos;');
const files = readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort();
const entries = [];

for (const f of files) {
  const raw = readFileSync(resolve(SRC, f), 'utf8').trim();
  const name = f.replace(/\.svg$/, '');
  const open = /<svg\b([^>]*)>/.exec(raw);
  if (!open) throw new Error(`${f}: no <svg> element`);
  const viewBox = /viewBox="([^"]+)"/.exec(open[1])?.[1] ?? '0 0 320 240';
  const title = /<title>([^<]*)<\/title>/.exec(raw)?.[1] ?? name;
  let body = raw.slice(open.index + open[0].length, raw.lastIndexOf('</svg>')).replace(/<title>[^<]*<\/title>/, '');
  const unknown = new Set();
  body = body.replace(/#[0-9A-Fa-f]{6}\b/g, (hex) => {
    const v = PLACEHOLDERS[hex.toUpperCase()];
    if (!v) unknown.add(hex);
    return v ?? hex;
  });
  if (unknown.size) console.warn(`  ! ${f}: literal colours not in PLACEHOLDERS: ${[...unknown].join(', ')} (left as-is)`);
  // fill / stroke that are CSS variables go into `style` (var() in presentation attributes is not reliable everywhere)
  body = body.replace(/<([a-zA-Z]+)\b([^>]*?)(\/?)>/g, (m, tag, attrs, close) => {
    const style = [];
    attrs = attrs.replace(/\s(fill|stroke)="(var\([^"]+\))"/g, (_, k, v) => {
      style.push(`${k}: '${v}'`);
      return '';
    });
    return `<${tag}${attrs}${style.length ? ` style={{ ${style.join(', ')} }}` : ''}${close}>`;
  });
  body = body.replace(/\s([a-z-:]+)=/g, (m, a) => ` ${ATTRS[a] ?? a}=`).replace(/\sstyle="[^"]*"/g, '');
  // transform="rotate(..)" etc. stay strings, which JSX accepts as-is
  entries.push({ name, viewBox, title, body });
}

const out = `// GENERATED by scripts/gen-illustrations.mjs from design/illustrations/*.svg — do not edit by hand.
// Colours are CSS variables (--ill-brand, --ill-brand-soft, --ill-accent, --ill-accent-soft, --ill-paper, --ill-ink).
import * as React from 'react';

export interface IllustrationDef {
  viewBox: string;
  title: string;
  body: React.ReactNode;
}

export const ILLUSTRATIONS = {
${entries.map((e) => `  '${e.name}': { viewBox: '${e.viewBox}', title: '${esc(e.title)}', body: (<>${e.body}</>) },`).join('\n')}
} as const satisfies Record<string, IllustrationDef>;

export type IllustrationName = keyof typeof ILLUSTRATIONS;
`;
writeFileSync(OUT, out);
console.log(`wrote ${entries.length} illustrations → src/components/illustrations/generated.tsx`);
