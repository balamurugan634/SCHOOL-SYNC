'use client';

import { useMutation, useQuery, useQueryClient, keepPreviousData } from '@tanstack/react-query';
import type { z } from 'zod';
import type {
  AttendanceRosterResponse,
  AttendanceSubmitBody,
  AttendanceSubmitResponse,
  AttendanceTodayResponse,
  FinanceSummaryOut,
  InvoiceDetailOut,
  InvoiceOut,
  ManagementDashboard,
  ParentDashboard,
  PaymentOut,
  paymentCreateBody,
} from '@school-sync/shared';
import { bff } from './fetcher';

export type Paged<T> = { data: T[]; meta: { page: number; pageSize: number; total: number; totalPages: number } };
export type PaymentCreate = z.infer<typeof paymentCreateBody>;

export const keys = {
  dashMgmt: ['dashboard', 'management'] as const,
  dashParent: (studentId?: string | null) => ['dashboard', 'parent', studentId ?? 'first'] as const,
  attToday: ['attendance', 'today'] as const,
  roster: (sectionId: string, date: string, periodId?: string | null) => ['attendance', 'roster', sectionId, date, periodId ?? ''] as const,
  invoices: ['fees', 'invoices'] as const,
  invoice: (id: string) => ['fees', 'invoice', id] as const,
  financeSummary: ['fees', 'summary'] as const,
};

export const useManagementDashboard = () => useQuery({ queryKey: keys.dashMgmt, queryFn: ({ signal }) => bff<ManagementDashboard>('/dashboard/management', { signal }), staleTime: 30_000 });

export const useParentDashboard = (studentId?: string | null, enabled = true) =>
  useQuery({
    queryKey: keys.dashParent(studentId),
    queryFn: ({ signal }) => bff<ParentDashboard>('/dashboard/parent', { query: { studentId: studentId ?? undefined }, signal }),
    staleTime: 30_000,
    enabled,
    placeholderData: keepPreviousData,
  });

export const useAttendanceToday = () => useQuery({ queryKey: keys.attToday, queryFn: ({ signal }) => bff<AttendanceTodayResponse>('/attendance/today', { signal }), staleTime: 15_000 });

export const useRoster = (sectionId: string | null, date: string, periodId?: string | null) =>
  useQuery({
    queryKey: keys.roster(sectionId ?? '', date, periodId),
    queryFn: ({ signal }) => bff<AttendanceRosterResponse>(`/attendance/sections/${sectionId}`, { query: { date, periodId: periodId ?? undefined }, signal }),
    enabled: !!sectionId,
    staleTime: 0,
    refetchOnMount: 'always',
  });

export function useSubmitRoster(sectionId: string) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (body: AttendanceSubmitBody) => bff<AttendanceSubmitResponse>(`/attendance/sections/${sectionId}`, { method: 'PUT', body }),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ['attendance'] });
      void qc.invalidateQueries({ queryKey: ['dashboard'] });
    },
  });
}

export interface InvoiceFilters {
  q?: string;
  status?: string;
  gradeId?: string;
  overdue?: boolean;
  from?: string;
  to?: string;
  page: number;
  pageSize: number;
}

export const invoiceQuery = (f: InvoiceFilters) => ({ q: f.q || undefined, status: f.status || undefined, gradeId: f.gradeId || undefined, overdue: f.overdue ? 'true' : undefined, from: f.from || undefined, to: f.to || undefined, page: f.page, pageSize: f.pageSize });

export const useInvoices = (f: InvoiceFilters) =>
  useQuery({ queryKey: [...keys.invoices, f], queryFn: ({ signal }) => bff<Paged<InvoiceOut>>('/fees/invoices', { query: invoiceQuery(f), signal }), placeholderData: keepPreviousData, staleTime: 15_000 });

export const useInvoice = (id: string | null) => useQuery({ queryKey: keys.invoice(id ?? ''), queryFn: ({ signal }) => bff<InvoiceDetailOut>(`/fees/invoices/${id}`, { signal }), enabled: !!id });

export const useFinanceSummary = (enabled = true) => useQuery({ queryKey: keys.financeSummary, queryFn: ({ signal }) => bff<FinanceSummaryOut>('/finance/summary', { signal }), enabled, staleTime: 60_000 });

export const useGrades = () => useQuery({ queryKey: ['academics', 'grades'], queryFn: ({ signal }) => bff<{ data: { id: string; name: string }[] } | { id: string; name: string }[]>('/academics/grades', { signal }).then((r) => (Array.isArray(r) ? r : r.data)), staleTime: 5 * 60_000 });

/** Offline payment. The Idempotency-Key is generated by the caller ONCE per attempt so a retry replays instead of repeating. */
export function useRecordPayment() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: ({ body, idempotencyKey }: { body: PaymentCreate; idempotencyKey: string }) => bff<PaymentOut>('/payments', { method: 'POST', body, headers: { 'idempotency-key': idempotencyKey } }),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ['fees'] });
      void qc.invalidateQueries({ queryKey: ['dashboard'] });
    },
  });
}
